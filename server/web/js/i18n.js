/* UI language: ?lang= override > stored toggle choice > browser language
   (any zh-* Accept-Language picks Chinese) > English. */
let lang = 'en';
try {
  if (typeof navigator !== 'undefined') {
    const prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''];
    if (prefs.some(l => /^zh\b/i.test(String(l)))) lang = 'zh';
  }
} catch (e) {}
try {
  if (typeof window !== 'undefined' && window.localStorage) lang = window.localStorage.getItem('pgext.lang') || lang;
} catch (e) {}
try {
  if (typeof location !== 'undefined') {
    const q = new URLSearchParams(location.search).get('lang');
    if (q === 'zh' || q === 'en') lang = q;
  }
} catch (e) {}

export const getLang = () => lang;
export function setLangValue(next) {
  if (next === 'zh' || next === 'en') lang = next;
}

export function t(k, vars) {
  const pair = I18N[k];
  let s = pair ? pair[lang === 'zh' ? 1 : 0] : k;
  if (vars) for (const [kk, vv] of Object.entries(vars)) s = s.replaceAll('{' + kk + '}', vv);
  return s;
}

export const bi = (en, zh) => (lang === 'zh' ? zh : en);
export const catName = c => { const p = CAT_NAMES[c]; return p ? p[lang === 'zh' ? 1 : 0] : c; };
export const desc = e => (lang === 'zh' && e.zh) ? e.zh : (e.en || e.zh || '');
